@app.post("/api/checkout")
def checkout():
    body = request.get_json(force=True, silent=True) or {}
    event = get_event(body.get("event_id"))
    name = (body.get("name") or "").strip()
    email = (body.get("email") or "").strip()
    try:
        quantity = int(body.get("qty", 1))
    except (TypeError, ValueError):
        quantity = 0
    if not event or not event["active"]:
        return err("Event not found.", 404)
    if not name or "@" not in email:
        return err("Enter your name and a valid email address.")
    if not 1 <= quantity <= 10:
        return err("Choose between 1 and 10 tickets.")
    if public(event)["left"] < quantity:
        return err("Not enough tickets left for this event.")
    if not SECRET:
        return err("Payments are not set up yet. Add PAYSTACK_SECRET_KEY to backend/.env.", 500)
    reference = "TP-" + uuid.uuid4().hex[:10].upper()
    amount = event["price"] * quantity * 100
    try:
        response = requests.post(f"{PAYSTACK}/transaction/initialize", headers=auth(), timeout=20, json={
            "email": email, "amount": amount, "currency": CURRENCY, "reference": reference,
            "callback_url": SITE_URL,
            "metadata": {"event_id": event["id"], "event": event["title"], "name": name, "qty": quantity},
        }).json()
    except requests.RequestException:
        return err("Could not reach Paystack. Try again in a moment.", 502)
    if not response.get("status"):
        return err(response.get("message", "Paystack could not start the payment."), 502)
    with db() as conn:
        conn.execute("INSERT INTO orders (ref, event_id, name, email, qty, amount) VALUES (%s, %s, %s, %s, %s, %s)",
                     (reference, event["id"], name, email, quantity, amount))
    return jsonify(authorization_url=response["data"]["authorization_url"], reference=reference)


@app.get("/api/verify/<ref>")
def verify(ref):
    try:
        response = requests.get(f"{PAYSTACK}/transaction/verify/{ref}", headers=auth(), timeout=20).json()
    except requests.RequestException:
        return err("Could not reach Paystack. Try again in a moment.", 502)
    if not response.get("status"):
        return err(response.get("message", "Payment not found."), 404)
    order = settle(response["data"])
    if not order:
        return err("Order not found.", 404)
    event = get_event(order["event_id"])
    download = f"/api/tickets/{ref}.pdf?t={dl.dumps(ref)}" if order["status"] == "paid" else None
    return jsonify(order=order, event=event["title"] if event else None, download=download)


@app.post("/api/paystack/webhook")
def webhook():
    signature = request.headers.get("x-paystack-signature", "")
    digest = hmac.new(SECRET.encode(), request.get_data(), hashlib.sha512).hexdigest()
    if not SECRET or not hmac.compare_digest(signature, digest):
        return "", 401
    event = request.get_json(silent=True) or {}
    if event.get("event") == "charge.success":
        settle(event.get("data") or {})
    return "", 200


def admin_required(function):
    @wraps(function)
    def wrapped(*args, **kwargs):
        try:
            tokens.loads(request.headers.get("Authorization", "").replace("Bearer ", ""), max_age=43200)
        except BadSignature:
            return err("Please sign in again.", 401)
        return function(*args, **kwargs)
    return wrapped


@app.post("/api/admin/login")
def admin_login():
    password = (request.get_json(silent=True) or {}).get("password", "")
    if not ADMIN_PASSWORD:
        return err("Set ADMIN_PASSWORD in backend/.env to enable the dashboard.", 500)
    if not hmac.compare_digest(password, ADMIN_PASSWORD):
        return err("Wrong password.", 401)
    return jsonify(token=tokens.dumps("admin"))


@app.get("/api/admin/summary")
@admin_required
def admin_summary():
    with db() as conn:
        totals = conn.execute("SELECT COALESCE(SUM(amount), 0) AS rev, COALESCE(SUM(qty), 0) AS tix, COUNT(*) AS n FROM orders WHERE status = 'paid'").fetchone()
        unpaid = conn.execute("SELECT COUNT(*) AS n FROM orders WHERE status != 'paid'").fetchone()["n"]
        revenues = {row["event_id"]: row["r"] for row in conn.execute(
            "SELECT event_id, SUM(amount) AS r FROM orders WHERE status = 'paid' GROUP BY event_id"
        ).fetchall()}
    event_rows = [{**public(event), "sold": sold(event["id"]), "revenue": revenues.get(event["id"], 0)}
                  for event in all_events(False)]
    return jsonify(revenue=totals["rev"], tickets=totals["tix"], paid_orders=totals["n"],
                   unpaid_orders=unpaid, events=event_rows)


