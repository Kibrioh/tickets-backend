def make_ticket_pdf(order):
    event = get_event(order["event_id"])
    if not event:
        raise ValueError("The event for this order no longer exists.")
    width, height = 612, 252
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=(width, height))
    cover = None
    if event["image"].startswith("/uploads/"):
        try:
            cover = ImageReader(Image.open(os.path.join(UPLOADS, os.path.basename(event["image"]))).convert("RGB"))
        except Exception:
            cover = None
    navy, muted = HexColor("#0B1F3A"), HexColor("#5B6B80")
    try:
        day = datetime.strptime(event["date"], "%Y-%m-%d").strftime("%a %d %b %Y")
    except ValueError:
        day = event["date"]

    for number in range(1, order["qty"] + 1):
        code = f'{order["ref"]}-{number}'
        pdf.setFillColor(white)
        pdf.rect(0, 0, width, height, fill=1, stroke=0)
        pdf.saveState()
        path = pdf.beginPath()
        path.rect(0, 0, 220, height)
        pdf.clipPath(path, stroke=0, fill=0)
        if cover:
            image_width, image_height = cover.getSize()
            scale = max(220 / image_width, height / image_height)
            pdf.drawImage(cover, (220 - image_width * scale) / 2, (height - image_height * scale) / 2,
                          image_width * scale, image_height * scale)
        else:
            pdf.setFillColor(HexColor(CAT_COLORS.get(event["category"], "#00B8D9")))
            pdf.rect(0, 0, 220, height, fill=1, stroke=0)
        pdf.setFillColor(HexColor("#061224"))
        pdf.setFillAlpha(0.8)
        pdf.rect(0, 0, 220, 34, fill=1, stroke=0)
        pdf.setFillAlpha(1)
        pdf.setFillColor(white)
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(14, 13, "TechPoint Solutions")
        pdf.restoreState()
        pdf.setStrokeColor(HexColor("#DCE3EA"))
        pdf.setDash(4, 4)
        pdf.line(470, 14, 470, height - 14)
        pdf.setDash()
        pdf.setFillColor(muted)
        pdf.setFont("Helvetica", 10)
        pdf.drawString(244, height - 30, "ADMIT ONE")
        pdf.setFillColor(navy)
        pdf.setFont("Helvetica-Bold", 19)
        y = height - 58
        for line in simpleSplit(event["title"], "Helvetica-Bold", 19, 215)[:2]:
            pdf.drawString(244, y, line)
            y -= 23
        pdf.setFont("Helvetica", 11)
        pdf.setFillColor(muted)
        for line in (day, f'{event["venue"]}, {event["city"]}', f'Holder: {order["name"]}',
                     f'Ticket {number} of {order["qty"]}'):
            pdf.drawString(244, y - 8, line)
            y -= 17
        qr = QrCodeWidget(code)
        bounds = qr.getBounds()
        drawing = Drawing(120, 120, transform=[120 / (bounds[2] - bounds[0]), 0, 0,
                                                120 / (bounds[3] - bounds[1]), 0, 0])
        drawing.add(qr)
        renderPDF.draw(drawing, pdf, 486, 92)
        pdf.setFillColor(navy)
        pdf.setFont("Helvetica-Bold", 9)
        pdf.drawCentredString(546, 76, code)
        pdf.setFont("Helvetica", 8)
        pdf.setFillColor(muted)
        pdf.drawCentredString(546, 62, "Scan or show at the gate")
        pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def send_receipt(order):
    host = os.getenv("SMTP_HOST")
    if not host:
        print("SMTP not configured, receipt skipped for", order["ref"])
        return
    event = get_event(order["event_id"])
    if not event:
        return
    total = f'KES {order["amount"] / 100:,.0f}'
    escape = html.escape
    message = EmailMessage()
    message["Subject"] = f'Your tickets for {event["title"]} ({order["ref"]})'
    message["From"] = os.getenv("MAIL_FROM") or os.getenv("SMTP_USER")
    message["To"] = order["email"]
    message.set_content(
        f'Hi {order["name"]},\n\nThank you for your purchase. Show this reference at the gate.\n\n'
        f'Reference: {order["ref"]}\nEvent: {event["title"]}\nDate: {event["date"]}\n'
        f'Venue: {event["venue"]}, {event["city"]}\nTickets: {order["qty"]}\n'
        f'Total paid: {total}\n\nTechPoint Solutions'
    )
    message.add_alternative(f"""<div style="font-family:Arial,sans-serif;max-width:520px;margin:auto;color:#0B1F3A">
<div style="background:#061224;color:#fff;padding:20px 24px;border-radius:12px 12px 0 0"><strong style="font-size:18px">TechPoint <span style="color:#00B8D9">Solutions</span></strong></div>
<div style="border:1px solid #DCE3EA;border-top:0;padding:24px;border-radius:0 0 12px 12px">
<p>Hi {escape(order["name"])}, your payment is confirmed. Your ticket is attached as a PDF. Show it at the gate.</p>
<p style="background:#E0F7FB;padding:14px;border-radius:8px;font-size:20px;font-weight:bold;letter-spacing:1px;text-align:center">{order["ref"]}</p>
<table style="width:100%;font-size:15px;line-height:1.8"><tr><td>Event</td><td align="right"><b>{escape(event["title"])}</b></td></tr>
<tr><td>Date</td><td align="right">{event["date"]}</td></tr><tr><td>Venue</td><td align="right">{escape(event["venue"])}, {escape(event["city"])}</td></tr>
<tr><td>Tickets</td><td align="right">{order["qty"]}</td></tr><tr><td>Total paid</td><td align="right"><b>{total}</b></td></tr></table></div></div>""", subtype="html")
    try:
        message.add_attachment(make_ticket_pdf(order), maintype="application", subtype="pdf",
                               filename=f'TechPoint-{order["ref"]}.pdf')
    except Exception as exc:
        print("Ticket PDF failed:", exc)
    try:
        port = int(os.getenv("SMTP_PORT", "587"))
        smtp_class = smtplib.SMTP_SSL if port == 465 else smtplib.SMTP
        with smtp_class(host, port, timeout=20) as server:
            if port != 465:
                server.starttls()
            server.login(os.getenv("SMTP_USER", ""), os.getenv("SMTP_PASS", ""))
            server.send_message(message)
    except Exception as exc:
        print("Receipt email failed:", exc)


def settle(data):
    reference = data.get("reference")
    paid_now = False
    with db() as conn:
        order = conn.execute("SELECT * FROM orders WHERE ref = %s", (reference,)).fetchone()
        if not order:
            return None
        if (data.get("status") == "success" and data.get("amount") == order["amount"]
                and data.get("currency", CURRENCY) == CURRENCY):
            paid_now = order["status"] != "paid"
            conn.execute("UPDATE orders SET status = 'paid' WHERE ref = %s", (reference,))
        elif data.get("status") in ("failed", "abandoned") and order["status"] != "paid":
            conn.execute("UPDATE orders SET status = %s WHERE ref = %s", (data["status"], reference))
        result = dict(conn.execute("SELECT * FROM orders WHERE ref = %s", (reference,)).fetchone())
    if paid_now:
        threading.Thread(target=send_receipt, args=(result,), daemon=True).start()
    return result


