@contextmanager
def db():
    """Yield a dict-row PostgreSQL connection; commit on success and roll back on error."""
    conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    try:
        with conn:
            yield conn
    finally:
        conn.close()


def initialize_database():
    with db() as conn:
        conn.execute("""CREATE TABLE IF NOT EXISTS events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL, category TEXT NOT NULL, venue TEXT NOT NULL, city TEXT NOT NULL,
            date TEXT NOT NULL, price INTEGER NOT NULL, capacity INTEGER NOT NULL,
            blurb TEXT NOT NULL DEFAULT '', featured BOOLEAN NOT NULL DEFAULT FALSE,
            active BOOLEAN NOT NULL DEFAULT TRUE, image TEXT NOT NULL DEFAULT '')""")
        conn.execute("""CREATE TABLE IF NOT EXISTS orders (
            ref TEXT PRIMARY KEY, event_id BIGINT REFERENCES events(id), name TEXT NOT NULL,
            email TEXT NOT NULL, qty INTEGER NOT NULL, amount INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'pending', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)""")
        conn.execute("ALTER TABLE events ADD COLUMN IF NOT EXISTS image TEXT NOT NULL DEFAULT ''")
        conn.execute("ALTER TABLE events ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE")
        conn.execute("ALTER TABLE orders ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP")
        if not conn.execute("SELECT 1 FROM events LIMIT 1").fetchone():
            for event in EVENTS:
                conn.execute(
                    """INSERT INTO events (title, category, venue, city, date, price, capacity, blurb, featured)
                       VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)""",
                    (event["title"], event["category"], event["venue"], event["city"], event["date"],
                     event["price"], event["capacity"], event["blurb"], event["featured"]),
                )


