def clean(body):
    image = (body.get("image") or "").strip()
    if image and not image.startswith(("/uploads/", "http://", "https://")):
        return None
    try:
        event = {
            "image": image,
            "title": body["title"].strip(),
            "category": body["category"],
            "venue": body["venue"].strip(),
            "city": body["city"].strip(),
            "date": body["date"],
            "price": int(body["price"]),
            "capacity": int(body["capacity"]),
            "blurb": (body.get("blurb") or "").strip(),
            "featured": bool(body.get("featured")),
            "active": bool(body.get("active", True)),
        }
    except (KeyError, ValueError, AttributeError, TypeError):
        return None
    if (not event["title"] or not event["date"]
            or event["category"] not in {category["id"] for category in CATEGORIES}
            or event["price"] < 0 or event["capacity"] < 1):
        return None
    return event


@app.post("/api/admin/events")
@admin_required
def admin_create_event():
    event = clean(request.get_json(silent=True) or {})
    if not event:
        return err("Fill in the title, date, category, price and capacity.")
    columns = list(event)
    placeholders = ", ".join(["%s"] * len(columns))
    with db() as conn:
        row = conn.execute(f"INSERT INTO events ({', '.join(columns)}) VALUES ({placeholders}) RETURNING id",
                           tuple(event[column] for column in columns)).fetchone()
    return jsonify(id=row["id"])


@app.put("/api/admin/events/<int:i>")
@admin_required
def admin_update_event(i):
    event = clean(request.get_json(silent=True) or {})
    if not event or not get_event(i):
        return err("Fill in the title, date, category, price and capacity.")
    assignments = ", ".join(f"{column} = %s" for column in event)
    with db() as conn:
        conn.execute(f"UPDATE events SET {assignments} WHERE id = %s", (*event.values(), i))
    return jsonify(ok=True)


@app.get("/api/tickets/<ref>.pdf")
def ticket_pdf(ref):
    try:
        valid = dl.loads(request.args.get("t", ""), max_age=60 * 60 * 24 * 365) == ref
    except BadSignature:
        valid = False
    if not valid:
        return err("This ticket link is not valid.", 403)
    with db() as conn:
        order = conn.execute("SELECT * FROM orders WHERE ref = %s AND status = 'paid'", (ref,)).fetchone()
    if not order:
        return err("Ticket not found, or the payment is not confirmed yet.", 404)
    return Response(make_ticket_pdf(dict(order)), mimetype="application/pdf",
                    headers={"Content-Disposition": f'attachment; filename="TechPoint-{ref}.pdf"'})


