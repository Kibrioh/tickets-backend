def row_event(row):
    event = dict(row)
    event["featured"] = bool(event["featured"])
    event["active"] = bool(event["active"])
    event["image"] = event.get("image") or ""
    return event


def all_events(active_only=True):
    query = "SELECT * FROM events"
    if active_only:
        query += " WHERE active = TRUE"
    query += " ORDER BY date"
    with db() as conn:
        rows = conn.execute(query).fetchall()
    return [row_event(row) for row in rows]


def get_event(event_id):
    with db() as conn:
        row = conn.execute("SELECT * FROM events WHERE id = %s", (event_id,)).fetchone()
    return row_event(row) if row else None


def sold(event_id):
    with db() as conn:
        row = conn.execute("SELECT COALESCE(SUM(qty), 0) AS n FROM orders WHERE event_id = %s AND status = 'paid'",
                           (event_id,)).fetchone()
    return row["n"]


def public(event):
    return {**event, "left": max(event["capacity"] - sold(event["id"]), 0)}


