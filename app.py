@app.post("/api/admin/upload")
@admin_required
def admin_upload():
    file = request.files.get("file")
    extension = os.path.splitext(file.filename or "")[1].lower() if file else ""
    if extension not in (".jpg", ".jpeg", ".png", ".webp"):
        return err("Upload a JPG, PNG or WebP image.")
    try:
        Image.open(file.stream).verify()
    except Exception:
        return err("That file is not a valid image.")
    file.stream.seek(0)
    name = uuid.uuid4().hex + extension
    file.save(os.path.join(UPLOADS, name))
    return jsonify(url=f"/uploads/{name}")


